// npm run lab: regenerates samples/lab/, the reproducible laboratory demonstration.
// Synthetic surrogate data only. See docs/laboratory-demo.md.
import { mkdirSync, rmSync, writeFileSync } from "node:fs";
import { createCipheriv, scryptSync } from "node:crypto";
import { sha256Hex, toBase64, utf8 } from "../src/core/bytes";
import { PEOPLE, SYNTHETIC } from "./lab-fixtures";
import { legacySample, runLab } from "./lab-scenario";

export const LAB_PASSPHRASE = "lab-demo-passphrase (public, demo only)";
const OUT = "samples/lab";
const json = (v: unknown) => JSON.stringify(v, null, 2) + "\n";

const run = await runLab({ legacySample: legacySample() });
const { lab, exchange } = run;
rmSync(OUT, { recursive: true, force: true });
for (const d of ["processes", "evidence", "ledgers", "exchange", "keys"]) mkdirSync(`${OUT}/${d}`, { recursive: true });

writeFileSync(`${OUT}/anchors.json`, json(lab.world.anchors));
writeFileSync(`${OUT}/trust-store.json`, json(lab.world.trustStore));
writeFileSync(`${OUT}/trust-store.signed.json`, json(lab.world.signedTrustStore));
writeFileSync(`${OUT}/authority.json`, lab.world.authorityBytes);
writeFileSync(`${OUT}/authority.signed.json`, json(lab.world.signedAuthority));
for (const p of lab.world.processes) writeFileSync(`${OUT}/processes/${p.definition.id}-v${p.definition.version}.json`, p.bytes);
writeFileSync(`${OUT}/SYN-PH-2000_A.tdp`, lab.revA.tdp);
writeFileSync(`${OUT}/SYN-PH-2000_B.tdp`, lab.revB.tdp);
for (const f of Object.values(lab.evidence)) writeFileSync(`${OUT}/evidence/${f.name}`, f.bytes);
for (const [name, L] of Object.entries(lab.ledgers)) writeFileSync(`${OUT}/ledgers/${name}.ledger.json`, json(L));
for (const [name, L] of Object.entries(run.invalid)) writeFileSync(`${OUT}/ledgers/${name}.ledger.json`, json(L));
writeFileSync(`${OUT}/ledgers/SN-0001.checkpoint.json`, json(run.checkpoint));
writeFileSync(`${OUT}/exchange/recipe.json`, json(exchange.recipe));
writeFileSync(`${OUT}/exchange/fixture-source.initial.json`, json(exchange.initial));
writeFileSync(`${OUT}/exchange/fixture-source.after.json`, json(exchange.after));
writeFileSync(`${OUT}/exchange/SN-0001.proposals.json`, json(exchange.proposals));
writeFileSync(`${OUT}/exchange/SN-0001.acks.json`, json(exchange.acks));
writeFileSync(`${OUT}/exchange/SN-0001.acks-replay.json`, json(exchange.replay));
writeFileSync(`${OUT}/exchange/SN-0002.proposals.json`, json(exchange.proposals2));
writeFileSync(`${OUT}/exchange/SN-0002.acks.json`, json(exchange.acks2));
writeFileSync(`${OUT}/evidence-bundle-SN-0001.json`, json(run.bundle));
writeFileSync(`${OUT}/demo-results.json`, json(run.demonstrations));

// Encrypted CLI key files for the walkthrough in docs/laboratory-demo.md. *.key.json is gitignored.
// The passphrase is public and the seeds are in tools/lab-fixtures.ts: these keys protect nothing.
const SCRYPT = { N: 1 << 14, r: 8, p: 1 };
for (const p of PEOPLE) {
  const k = lab.world.keys[p.id]!;
  const salt = utf8.encode(`lab-salt/${p.id}`.padEnd(16, ".")).slice(0, 16);
  const iv = utf8.encode(`lab-iv/${p.id}`.padEnd(12, ".")).slice(0, 12);
  const cipher = createCipheriv("aes-256-gcm", scryptSync(LAB_PASSPHRASE.normalize("NFC"), salt, 32, { ...SCRYPT, maxmem: 256 * SCRYPT.N * SCRYPT.r }), iv);
  cipher.setAAD(Buffer.from(k.publicKey));
  const data = Buffer.concat([cipher.update(k.pkcs8), cipher.final()]);
  const file = {
    schema: "tdp-key/0.1", keyId: k.keyId, name: p.name, roles: p.signing, publicKey: k.publicKey,
    kdf: { alg: "scrypt", ...SCRYPT, salt: toBase64(salt) },
    cipher: { alg: "AES-256-GCM", iv: toBase64(iv), tag: toBase64(cipher.getAuthTag()), data: toBase64(data) },
  };
  writeFileSync(`${OUT}/keys/${p.id}.key.json`, json(file), { mode: 0o600 });
}

const rows = run.demonstrations.map((d) => `| ${d.id} | ${d.scenario} | ${d.expected} | ${d.actual.replace(/\|/g, "\\|").slice(0, 260)} | ${d.pass ? "PASS" : "**FAIL**"} |`);
const perf = run.performance.map((p) => `| ${p.metric} | ${p.value} ${p.unit} | ${p.note} |`);
writeFileSync(`${OUT}/demo-results.md`, `# Laboratory demonstration results

Generated by \`npm run lab\` (evaluation time ${run.bundle.configuration.evaluatedAt}). ${SYNTHETIC}

These are **software behaviour** results on synthetic fixtures. No physical build, inspection or
source-system release is represented; see docs/laboratory-demo.md for the evidence/gap matrix.

| ID | Scenario | Expected | Actual | Result |
|---|---|---|---|---|
${rows.join("\n")}

## Measured software performance (this machine)

| Metric | Value | Note |
|---|---|---|
${perf.join("\n")}

${run.demonstrations.filter((d) => d.pass).length} of ${run.demonstrations.length} demonstrations passed.
`);

const failed = run.demonstrations.filter((d) => !d.pass);
console.log(`wrote ${OUT}/: packages A and B, ${Object.keys(lab.ledgers).length} ledgers + ${Object.keys(run.invalid).length} invalid/truncated, exchange files, evidence bundle (sha256 ${(await sha256Hex(utf8.encode(json(run.bundle)))).slice(0, 16)}…)`);
console.log(`${run.demonstrations.length - failed.length}/${run.demonstrations.length} demonstrations passed`);
for (const d of failed) console.log(`FAIL ${d.id}: ${d.actual}`);
process.exit(failed.length ? 1 : 0);
